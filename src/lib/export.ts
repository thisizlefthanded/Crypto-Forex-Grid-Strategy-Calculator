import { getAsset } from './assets';
import type { GridConfig } from './config';
import type { GridResult } from './engine';
import { stepDecimals } from './format';

const r = (v: number, d: number) => Number(v.toFixed(d));

export function toJson(cfg: GridConfig, res: GridResult): string {
  const d = cfg.digits;
  const asset = getAsset(cfg.assetId);
  return JSON.stringify(
    {
      schema: 'gridcalc/strategy@1',
      generatedAt: new Date().toISOString(),
      symbol: asset.symbol,
      config: cfg,
      summary: res.valid
        ? {
            gridStep: r(res.step, d + 2),
            gridStepPips: r(res.stepPips, 2),
            orders: res.orders.length,
            avgNetProfitPerGridUsd: r(res.profit.avgNetUsd, 2),
            maxDrawdownUsd: r(res.maxDrawdownUsd, 2),
            maxDrawdownPct: r(res.maxDrawdownPct, 2),
            maxMarginUsd: r(res.totals.maxMarginUsd, 2),
            stopOutPriceDown: res.stopOut.down === null ? null : r(res.stopOut.down, d),
            stopOutPriceUp: res.stopOut.up === null ? null : r(res.stopOut.up, d),
            estMonthlyRoiPct: r(res.projection.monthlyRoiPct, 2),
          }
        : null,
      orders: res.orders.map((o) => ({
        side: o.side,
        entry: r(o.entry, d),
        takeProfit: r(o.takeProfit, d),
        volume: o.volume,
        netProfitUsd: r(o.netProfitUsd, 2),
      })),
    },
    null,
    2,
  );
}

/** MetaTrader 4/5 `.set` preset — generic key names most grid EAs map 1:1. */
export function toMetaTraderSet(cfg: GridConfig, res: GridResult): string {
  const asset = getAsset(cfg.assetId);
  const d = cfg.digits;
  const points = (v: number) => Math.round(v / 10 ** -d);
  const lotDigits = stepDecimals(cfg.volumeStep);
  const dir = { long: 0, short: 1, neutral: 2 }[cfg.direction];
  const lotMode = { equal: 0, martingale: 1, arithmetic: 2 }[cfg.allocation];
  const baseLot = res.orders.find((o) => o.depth === 0)?.volume ?? cfg.baseVolume;

  const lines = [
    `; Grid strategy preset for ${asset.symbol} — generated by GridCalc`,
    `; ${new Date().toISOString()}`,
    '; Load in MetaTrader: EA properties → Inputs → Load. Rename keys if your EA uses different input names.',
    `; Direction: 0=Buy only, 1=Sell only, 2=Both | LotMode: 0=Fixed, 1=Martingale, 2=Arithmetic`,
    `InpSymbol=${asset.id}`,
    `InpDirection=${dir}`,
    `InpUpperPrice=${cfg.upperPrice.toFixed(d)}`,
    `InpLowerPrice=${cfg.lowerPrice.toFixed(d)}`,
    `InpGridLevels=${cfg.grids}`,
    `InpGeometric=${cfg.spacing === 'geometric' ? 'true' : 'false'}`,
    `InpGridStepPoints=${points(res.step)}`,
    `InpTakeProfitPoints=${points(res.step)}`,
    `InpLotSize=${baseLot.toFixed(lotDigits)}`,
    `InpLotMode=${lotMode}`,
    `InpLotMultiplier=${cfg.martingaleMultiplier}`,
    `InpLotIncrement=${cfg.arithmeticIncrement}`,
    `InpUseTrailing=${cfg.trailingEnabled ? 'true' : 'false'}`,
    `InpTrailingStartPoints=${points(res.step * (1 + cfg.trailingDistancePct / 100))}`,
    `InpTrailingStopPoints=${points((res.step * cfg.trailingDistancePct) / 100)}`,
    `InpMaxDrawdownPct=${Math.ceil(res.maxDrawdownPct * 1.1)}`,
    `InpMagicNumber=${20260000 + cfg.grids}`,
    '',
    '; ---- Level map (side, entry, TP, lots) ----',
    ...res.orders.map(
      (o, i) => `; L${String(i + 1).padStart(2, '0')} ${o.side.toUpperCase().padEnd(4)} ${o.entry.toFixed(d)}  TP ${o.takeProfit.toFixed(d)}  ${o.volume.toFixed(lotDigits)} lot`,
    ),
  ];
  return lines.join('\r\n') + '\r\n';
}

/** Ready-to-run CCXT script. Defaults to dry run. */
export function toCcxtPython(cfg: GridConfig, res: GridResult): string {
  const asset = getAsset(cfg.assetId);
  const d = cfg.digits;
  const volDigits = stepDecimals(cfg.volumeStep);
  const amountOf = (v: number) => (asset.volumeUnit === 'coins' ? v : v * cfg.contractSize);
  const rows = res.orders
    .map((o) => `    ("${o.side}", ${o.entry.toFixed(d)}, ${o.takeProfit.toFixed(d)}, ${amountOf(o.volume).toFixed(asset.volumeUnit === 'coins' ? volDigits : 0)}),`)
    .join('\n');
  return `"""
Grid strategy for ${asset.symbol} — generated by GridCalc (${new Date().toISOString()})
Range ${cfg.lowerPrice.toFixed(d)} – ${cfg.upperPrice.toFixed(d)}, ${cfg.grids} grids (${cfg.spacing}), direction: ${cfg.direction}

pip install ccxt
Set API_KEY / API_SECRET in your environment and flip DRY_RUN to False when ready.
Amounts are in base-asset units. This places the entry limits only; attach TPs
as each entry fills (see on_fill) or let your bot loop manage them.
"""
import os
import ccxt

EXCHANGE_ID = "binance"          # any ccxt exchange id
SYMBOL = "${asset.symbol.endsWith('/USD') ? asset.symbol + 'T' : asset.symbol}"
DRY_RUN = True

# (side, entry_price, take_profit_price, amount)
GRID = [
${rows}
]


def make_exchange():
    cls = getattr(ccxt, EXCHANGE_ID)
    return cls({
        "apiKey": os.environ.get("API_KEY", ""),
        "secret": os.environ.get("API_SECRET", ""),
        "enableRateLimit": True,
    })


def place_grid(exchange):
    exchange.load_markets()
    for side, price, tp, amount in GRID:
        amount = float(exchange.amount_to_precision(SYMBOL, amount))
        price = float(exchange.price_to_precision(SYMBOL, price))
        if DRY_RUN:
            print(f"[dry-run] {side:4} {amount} @ {price}  -> TP {tp}")
            continue
        order = exchange.create_limit_order(SYMBOL, side, amount, price)
        print(f"placed {order['id']} {side} {amount} @ {price}")


def on_fill(exchange, side, amount, tp):
    """Call when an entry fills: places the opposite take-profit order."""
    exit_side = "sell" if side == "buy" else "buy"
    return exchange.create_limit_order(SYMBOL, exit_side, amount, tp)


if __name__ == "__main__":
    place_grid(make_exchange())
`;
}

export function toCsv(cfg: GridConfig, res: GridResult): string {
  const d = cfg.digits;
  const header = 'level,side,entry,take_profit,volume,notional_usd,margin_usd,gross_profit_usd,cost_usd,net_profit_usd,net_profit_pct';
  const rows = res.orders.map((o, i) =>
    [i + 1, o.side, o.entry.toFixed(d), o.takeProfit.toFixed(d), o.volume, o.notionalUsd.toFixed(2), o.marginUsd.toFixed(2), o.grossProfitUsd.toFixed(2), o.costUsd.toFixed(2), o.netProfitUsd.toFixed(2), o.netProfitPct.toFixed(4)].join(','),
  );
  return [header, ...rows].join('\n') + '\n';
}

export function downloadText(filename: string, content: string, mime = 'text/plain') {
  const blob = new Blob([content], { type: `${mime};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export async function copyText(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    const ok = document.execCommand('copy');
    ta.remove();
    return ok;
  }
}
